test('schedule, edit without losing date/time, clear description, and delete', async ({ page, request }) => {
  await page.goto('/meetings/schedule')
  const start = new Date(Date.now() + 3 * 86_400_000)
  const date = `${start.getFullYear()}-${String(start.getMonth() + 1).padStart(2, '0')}-${String(start.getDate()).padStart(2, '0')}`
  await page.getByRole('textbox', { name: 'Topic', exact: true }).fill('Browser regression meeting')
  await page.getByRole('button', { name: 'Add Description', exact: true }).click()
  await page.getByRole('textbox', { name: 'Description', exact: true }).fill('Original description')
  await page.getByLabel('Meeting date', { exact: true }).fill(date)
  await page.getByLabel('Meeting time', { exact: true }).fill('02:35')
  await page.getByLabel('AM or PM', { exact: true }).selectOption('PM')
  await page.getByLabel('Duration hours', { exact: true }).selectOption('1')
  await page.getByLabel('Duration minutes', { exact: true }).selectOption('0')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page).toHaveURL(/\/meetings$/)
  const meetings = await (await request.get(`${API}/api/meetings/?type=upcoming`)).json()
  const m = meetings.find((meeting: { title: string }) => meeting.title === 'Browser regression meeting')
  expect(m).toBeTruthy(); created.push(m.id)
  expect(new Date(m.start_time).getTime()).toBe(new Date(`${date}T14:35:00`).getTime())
  const row = page.getByRole('button', { name: 'Details for Browser regression meeting' })
  await row.hover()
  await row.getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByLabel('Meeting date', { exact: true })).toHaveValue(date)
  await expect(page.getByLabel('Meeting time', { exact: true })).toHaveValue('02:35')
  await expect(page.getByLabel('AM or PM', { exact: true })).toHaveValue('PM')
  await page.getByRole('textbox', { name: 'Description', exact: true }).fill('')
  await page.getByRole('button', { name: 'Update', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const edited = await (await request.get(`${API}/api/meetings/${m.id}`)).json()
  expect(edited.start_time).toBe(m.start_time)
  expect(edited.description).toBe('')
  await row.hover()
  page.once('dialog', (dialog) => dialog.accept())
  await row.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(row).toHaveCount(0)
})

test('instant meeting generates ID and invite link, enters room, and preserves guest name', async ({ page, context, request }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'New Meeting', exact: true }).click()
  await expect(page).toHaveURL(/\/room\/\d{11}$/)
  const mid = page.url().split('/').pop()!
  const m = await (await request.post(`${API}/api/meetings/validate`, { data: { meeting_input: mid } })).json()
  created.push(m.id)
  await expect(page.getByRole('button', { name: 'Use microphone and camera', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Use microphone and camera', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Participants', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'More', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText(`/join?mid=${mid}`)
  await page.getByRole('button', { name: 'Copy URL', exact: true }).click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe(`http://localhost:3001/join?mid=${mid}`)
  await page.keyboard.press('Escape')
  await expect.poll(() => page.locator('video').evaluate((video: HTMLVideoElement) => Boolean(video.srcObject))).toBeTruthy()
  await page.getByRole('button', { name: 'Stop Video', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Start Video', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Start Video', exact: true }).click()
  await expect.poll(() => page.locator('video').evaluate((video: HTMLVideoElement) => Boolean(video.srcObject))).toBeTruthy()

  const guest = await context.newPage()
  await guest.goto(`/join?mid=${mid}`)
  await expect(guest.getByRole('textbox', { name: 'Meeting ID or invite link' })).toHaveValue(mid)
  await guest.getByRole('button', { name: 'Join', exact: true }).click()
  await guest.getByRole('button', { name: 'Join from your browser', exact: true }).click()
  await guest.getByRole('textbox', { name: 'Your Name' }).fill('Browser Guest')
  await guest.getByRole('button', { name: 'Join Meeting', exact: true }).click()
  await expect(guest).toHaveURL(/guest=1/)
  await guest.getByRole('button', { name: 'Continue without microphone and camera', exact: true }).click()
  await expect(guest.getByText('Browser Guest (me)', { exact: true })).toBeVisible()
  const participants = await (await request.get(`${API}/api/meetings/${m.id}/participants/`)).json()
  expect(participants.filter((p: { display_name: string }) => p.display_name === 'Browser Guest')).toHaveLength(1)
  await page.getByRole('button', { name: 'End', exact: true }).click()
  await page.getByRole('button', { name: 'End Meeting for All', exact: true }).click()
  await expect(page).toHaveURL(/\/meetings$/)
  expect((await (await request.get(`${API}/api/meetings/${m.id}`)).json()).status).toBe('ended')
  expect(errors).toEqual([])
  await guest.close()
})

