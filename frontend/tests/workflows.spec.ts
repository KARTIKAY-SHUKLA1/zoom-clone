test('joining can retry a temporary API failure without duplicate participants', async ({ page, request }) => {
  const m = await (await request.post(`${API}/api/meetings/instant`)).json()
  created.push(m.id)
  await page.goto(`/join?mid=${m.meeting_id}`)
  await page.getByRole('button', { name: 'Join', exact: true }).click()
  await page.getByRole('button', { name: 'Join from your browser', exact: true }).click()
  await page.getByRole('textbox', { name: 'Your Name' }).fill('Retry Guest')
  await page.getByRole('button', { name: 'Join Meeting', exact: true }).click()
  let failed = false
  await page.route('**/api/meetings/*/participants/', async (route) => {
    if (route.request().method() === 'GET' && !failed) {
      failed = true
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Temporary server error' }) })
    } else await route.continue()
  })
  await page.getByRole('button', { name: 'Continue without microphone and camera', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Temporary server error' })).toBeVisible()
  await page.getByRole('button', { name: 'Continue without microphone and camera', exact: true }).click()
  await expect(page.getByText('Retry Guest (me)', { exact: true })).toBeVisible()
  const participants = await (await request.get(`${API}/api/meetings/${m.id}/participants/`)).json()
  expect(participants.filter((p: { display_name: string }) => p.display_name === 'Retry Guest')).toHaveLength(1)
})

