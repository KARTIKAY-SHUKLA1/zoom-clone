test('date range filters stored meetings and Escape closes the calendar', async ({ page, request }) => {
  const start = new Date(Date.now() + 10 * 86_400_000)
  const m = await (await request.post(`${API}/api/meetings/`, { data: {title:'Date range regression', start_time:start.toISOString(), duration_minutes:40, time_zone:'UTC'} })).json()
  expect(m.id).toBeTruthy(); created.push(m.id)
  await page.goto('/meetings')
  await expect(page.getByRole('button', {name:'Details for Date range regression'})).toBeVisible()
  await page.getByRole('button', {name:'Choose meeting date range'}).click()
  await expect(page.getByRole('dialog', {name:'Meeting date range'})).toBeVisible()
  const from = new Date(start); from.setDate(from.getDate() + 1)
  const date = `${from.getFullYear()}-${String(from.getMonth() + 1).padStart(2,'0')}-${String(from.getDate()).padStart(2,'0')}`
  await page.getByLabel('From date', {exact:true}).fill(date)
  await expect(page.getByRole('button', {name:'Details for Date range regression'})).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', {name:'Meeting date range'})).toHaveCount(0)
})

test('editing a start time by one minute preserves the change when stored seconds are present', async ({ page, request }) => {
  const start = new Date(Date.now() + 3 * 86_400_000)
  start.setHours(14, 35, 59, 0)
  const m = await (await request.post(`${API}/api/meetings/`, {data: {
    title:'Minute boundary regression', start_time:start.toISOString(), duration_minutes:40, time_zone:'UTC',
  }})).json()
  expect(m.id).toBeTruthy(); created.push(m.id)
  await page.goto(`/meetings?selected=${m.id}`)
  const row = page.getByRole('button', {name:'Details for Minute boundary regression'})
  await row.hover()
  await row.getByRole('button', {name:'Edit', exact:true}).click()
  await page.getByLabel('Meeting time', {exact:true}).fill('02:36')
  await page.getByRole('button', {name:'Update', exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const edited = await (await request.get(`${API}/api/meetings/${m.id}`)).json()
  start.setHours(14, 36, 0, 0)
  expect(new Date(edited.start_time).getTime()).toBe(start.getTime())
})
